/**
 * ============================================================================
 * UNIVERSAL DATA INTELLIGENCE PLATFORM (UDIP)
 * Module: workspace/communication/report-generator.js
 * ============================================================================
 * Comprehensive Analytical Report Generator (Markdown & Formatted HTML).
 * 
 * Generates publication-ready comprehensive analytical reports capturing:
 * - Dataset Overview & Epistemic Boundaries
 * - Executive Inquiries & Decision Summary
 * - Top Synthesized Findings & Statistical Evidence
 * - Predictive Model Governance & Leaderboard
 * - Active Risks, Opportunities, and What-If Projections
 * - Chronological Milestones & Version Audits
 * - Explicit Epistemological Guardrails & Limitations
 * ============================================================================
 */

(function (window) {
    'use strict';

    const ReportGenerator = {
        /**
         * Generate full Markdown report
         * 
         * @param {Object} workspaceReport
         * @returns {string} GitHub Flavored Markdown
         */
        generateMarkdown(workspaceReport = {}) {
            const meta = workspaceReport.metadata || {};
            const exec = workspaceReport.executiveMode || {};
            const narrative = workspaceReport.narrative || {};
            const evidence = workspaceReport.evidenceMode || {};
            const timeline = workspaceReport.timeline || {};
            const comparison = workspaceReport.versionComparison || {};

            let md = `# Comprehensive Analytical Intelligence Report\n\n`;
            md += `*Generated by Universal Data Intelligence Platform (UDIP)*  \n`;
            md += `**Dataset**: ${meta.datasetName || 'Dataset'} | **Rows**: ${(meta.rowCount || 0).toLocaleString()} | **Columns**: ${meta.columnCount || 0} | **Date**: ${new Date(meta.generatedAt || Date.now()).toISOString().split('T')[0]}\n\n`;
            md += `---\n\n`;

            // 1. Executive Summary
            md += `## 1. Executive Decision Summary\n\n`;
            if (narrative.headline) {
                md += `> **Key Empirical Signal**: ${narrative.headline}\n\n`;
            }
            if (exec.inquiries) {
                exec.inquiries.forEach(inq => {
                    md += `### ${inq.question}\n${inq.answer}\n\n`;
                });
            }

            // 2. Data Universe & Quality Profile
            md += `## 2. Data Universe & Epistemic Boundaries\n\n`;
            md += `${narrative.context || 'Dataset audited under universal profiling.'}\n\n`;
            if (exec.kpis) {
                md += `- **Data Quality Score**: ${exec.kpis.dataHealthScore}/100\n`;
                md += `- **Overall Epistemic Confidence**: ${exec.kpis.overallConfidence}%\n\n`;
            }

            // 3. Top Empirical Findings
            md += `## 3. Top Empirical Findings & Drivers\n\n`;
            if (narrative.topFindings && narrative.topFindings.length > 0) {
                narrative.topFindings.forEach((f, idx) => {
                    md += `### 3.${idx + 1} ${f.title}\n`;
                    md += `- **Statement**: ${f.statement}\n`;
                    md += `- **Category**: ${f.category} | **Importance**: ${f.importance}/100 | **Confidence**: ${f.confidence}%\n\n`;
                });
            }

            // 4. Risks & Opportunities
            md += `## 4. Risks & Optimization Levers\n\n`;
            if (narrative.risks && narrative.risks.length > 0) {
                md += `### Active Risks\n`;
                narrative.risks.forEach(r => {
                    md += `- **${r.title}** (Score: ${r.score}): ${r.statement}\n`;
                });
                md += `\n`;
            }
            if (narrative.opportunities && narrative.opportunities.length > 0) {
                md += `### Optimization Levers\n`;
                narrative.opportunities.forEach(o => {
                    md += `- **${o.title}** (Score: ${o.score}): ${o.statement}\n`;
                });
                md += `\n`;
            }

            // 5. Version Comparison
            if (comparison.dimensions) {
                md += `## 5. State & Evolution Audit\n\n`;
                md += `| Analytical Dimension | Status | Current State | Baseline / Prior |\n`;
                md += `| :--- | :--- | :--- | :--- |\n`;
                comparison.dimensions.forEach(d => {
                    md += `| ${d.name} | ${d.status} | ${d.current} | ${d.previous} |\n`;
                });
                md += `\n`;
            }

            // 6. Chronological Milestones
            if (timeline.events && timeline.events.length > 0) {
                md += `## 6. Analytical Timeline\n\n`;
                timeline.events.forEach(ev => {
                    md += `- **[${ev.step}] ${ev.title}**: ${ev.description}\n`;
                });
                md += `\n`;
            }

            // 7. Epistemological Limitations
            md += `## 7. Epistemological Guardrails & Limitations\n\n`;
            if (narrative.limitations) {
                narrative.limitations.forEach(lim => {
                    md += `- ${lim}\n`;
                });
            }
            md += `\n`;

            return md;
        },

        /**
         * Generate self-contained, beautifully styled HTML report
         * 
         * @param {Object} workspaceReport
         * @returns {string} HTML Document string
         */
        generateHTML(workspaceReport = {}) {
            const md = this.generateMarkdown(workspaceReport);
            const meta = workspaceReport.metadata || {};

            // Simple robust Markdown to HTML converter for standard elements
            let bodyHtml = md
                .replace(/^# (.*$)/gim, '<h1 class="rep-h1">$1</h1>')
                .replace(/^## (.*$)/gim, '<h2 class="rep-h2">$1</h2>')
                .replace(/^### (.*$)/gim, '<h3 class="rep-h3">$1</h3>')
                .replace(/^> (.*$)/gim, '<blockquote class="rep-quote">$1</blockquote>')
                .replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>')
                .replace(/\*(.*?)\*/gim, '<em>$1</em>')
                .replace(/^- (.*$)/gim, '<li>$1</li>')
                .replace(/\n\n/gim, '<br/><br/>');

            return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Analytical Intelligence Report — ${meta.datasetName || 'Dataset'}</title>
<style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; line-height: 1.6; color: #1e293b; background: #f8fafc; padding: 40px; margin: 0; }
    .report-container { max-width: 900px; margin: 0 auto; background: #ffffff; padding: 48px; border-radius: 12px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); }
    .rep-h1 { color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 12px; margin-top: 0; font-size: 28px; }
    .rep-h2 { color: #1e293b; margin-top: 32px; border-bottom: 1px solid #f1f5f9; padding-bottom: 8px; font-size: 20px; }
    .rep-h3 { color: #334155; margin-top: 20px; font-size: 16px; }
    .rep-quote { border-left: 4px solid #38bdf8; background: #f0f9ff; padding: 12px 16px; border-radius: 4px; margin: 16px 0; color: #0369a1; font-weight: 500; }
    li { margin-bottom: 6px; }
    table { width: 100%; border-collapse: collapse; margin: 16px 0; font-size: 14px; }
    th, td { padding: 10px 14px; border: 1px solid #e2e8f0; text-align: left; }
    th { background: #f1f5f9; font-weight: 600; }
    @media print { body { background: #fff; padding: 0; } .report-container { box-shadow: none; padding: 0; } }
</style>
</head>
<body>
<div class="report-container">
${bodyHtml}
</div>
</body>
</html>`;
        }
    };

    if (typeof window !== 'undefined') {
        window.UDIP = window.UDIP || {};
        window.UDIP.ReportGenerator = ReportGenerator;
    }
    if (typeof module !== 'undefined' && module.exports) {
        module.exports = ReportGenerator;
    }
})(typeof window !== 'undefined' ? window : global);

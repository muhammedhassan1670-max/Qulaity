/**
 * ============================================================================
 * UNIVERSAL DATA INTELLIGENCE PLATFORM (UDIP)
 * Module: workspace/communication/insight-exporter.js
 * ============================================================================
 * Targeted Analytical Briefs & Modular Exporter.
 * 
 * Generates tailored export packages for stakeholders:
 * 1. Executive Brief (1-page leadership summary)
 * 2. Analytical Finding Brief (granular single-insight dossier)
 * 3. Model Review Brief (ML architecture, metrics & governance)
 * 4. Decision Brief (ranked options, trade-offs & mitigations)
 * 5. Investigation Summary Brief (hypothesis tests, simulations, conclusion)
 * 
 * Supports Markdown, JSON, and formatted plain text representations.
 * ============================================================================
 */

(function (window) {
    'use strict';

    const InsightExporter = {
        /**
         * Export an Executive Brief
         * @param {Object} executiveData
         * @returns {Object} { markdown, json, text }
         */
        exportExecutiveBrief(executiveData = {}) {
            const title = executiveData.title || 'Executive Decision Briefing';
            const kpis = executiveData.kpis || {};
            const inquiries = executiveData.inquiries || [];

            let md = `# ${title}\n\n`;
            md += `Generated by Universal Data Intelligence Platform (UDIP)\n\n`;
            md += `## Key Performance Indicators\n`;
            md += `- **Data Health**: ${kpis.dataHealthScore ?? 'N/A'}/100\n`;
            md += `- **Model Accuracy**: ${kpis.modelAccuracyScore ? kpis.modelAccuracyScore + '%' : 'N/A'}\n`;
            md += `- **Active Risks**: ${kpis.activeRisksCount ?? 0}\n`;
            md += `- **Active Opportunities**: ${kpis.activeOpportunitiesCount ?? 0}\n`;
            md += `- **Overall Confidence**: ${kpis.overallConfidence ?? 80}%\n\n`;

            md += `## Leadership Inquiries\n`;
            inquiries.forEach(inq => {
                md += `### ${inq.question}\n${inq.answer}\n\n`;
            });

            return {
                markdown: md,
                json: JSON.stringify(executiveData, null, 2),
                text: md.replace(/[#*`]/g, '')
            };
        },

        /**
         * Export an Analytical Finding Brief
         * @param {Object} finding
         * @param {Object} reasoningChain
         * @returns {Object} { markdown, json, text }
         */
        exportFindingBrief(finding = {}, reasoningChain = null) {
            let md = `# Analytical Finding Brief: ${finding.title || 'Finding'}\n\n`;
            md += `**Category**: ${finding.category || 'General'} | **Importance**: ${finding.importance || 50}/100 | **Confidence**: ${finding.confidence || 50}%\n\n`;
            md += `## Empirical Statement\n${finding.statement || 'No description available.'}\n\n`;

            if (reasoningChain?.chain) {
                const c = reasoningChain.chain;
                md += `## Technical Reasoning Chain\n`;
                md += `- **Observation**: ${c.observation}\n`;
                md += `- **Descriptive Evidence**: ${c.evidence}\n`;
                md += `- **Statistical Support**: ${c.statisticalSupport}\n`;
                md += `- **Interpretation**: ${c.interpretation}\n`;
                md += `- **Implication**: ${c.implication}\n`;
                md += `- **Potential Decision**: ${c.potentialDecision}\n\n`;
            }

            if (finding.action) {
                md += `## Recommended Action\n${finding.action}\n\n`;
            }

            return {
                markdown: md,
                json: JSON.stringify({ finding, reasoningChain }, null, 2),
                text: md.replace(/[#*`]/g, '')
            };
        },

        /**
         * Export a Model Review Brief
         * @param {Object} analytics
         * @returns {Object} { markdown, json, text }
         */
        exportModelReviewBrief(analytics = {}) {
            const best = analytics?.leaderboard?.bestModel || {};
            const fi = analytics?.interpretation?.featureImportances || [];

            let md = `# Predictive Model Review & Governance Brief\n\n`;
            md += `## Champion Architecture\n`;
            md += `- **Model**: ${best.name || best.modelName || 'Algorithm'}\n`;
            md += `- **Target Variable**: ${analytics.targetColumn || 'Target'}\n`;
            md += `- **Validation Score**: ${best.score != null ? (best.score * 100).toFixed(2) + '%' : 'N/A'}\n`;
            md += `- **Task Type**: ${analytics.taskType || 'Supervised Learning'}\n\n`;

            md += `## Primary Predictive Drivers\n`;
            fi.slice(0, 5).forEach((f, idx) => {
                md += `${idx + 1}. **${f.variable}**: ${(f.importance * 100).toFixed(1)}% contribution\n`;
            });
            md += `\n`;

            return {
                markdown: md,
                json: JSON.stringify(analytics, null, 2),
                text: md.replace(/[#*`]/g, '')
            };
        },

        /**
         * Export an Investigation Summary Brief
         * @param {Object} briefData
         * @returns {Object} { markdown, json, text }
         */
        exportInvestigationBrief(briefData = {}) {
            let md = `# Investigation Brief: ${briefData.title || 'Guided Investigation'}\n\n`;
            md += `**Target Variable**: ${briefData.targetVariable || 'N/A'} | **Status**: ${briefData.status || 'OPEN'}\n\n`;
            md += `- **Hypotheses Tested**: ${briefData.totalHypothesesTested || 0}\n`;
            md += `- **Supported**: ${briefData.supportedCount || 0} | **Rejected**: ${briefData.rejectedCount || 0}\n`;
            md += `- **Simulations Run**: ${briefData.simulationsRun || 0}\n\n`;

            if (briefData.latestConclusion) {
                md += `## Conclusion & Decision\n${briefData.latestConclusion.summary}\n`;
                md += `**Action**: ${briefData.latestConclusion.decisionAction}\n`;
                md += `**Confidence**: ${briefData.latestConclusion.evidenceConfidence}%\n\n`;
            }

            return {
                markdown: md,
                json: JSON.stringify(briefData, null, 2),
                text: md.replace(/[#*`]/g, '')
            };
        }
    };

    if (typeof window !== 'undefined') {
        window.UDIP = window.UDIP || {};
        window.UDIP.InsightExporter = InsightExporter;
    }
    if (typeof module !== 'undefined' && module.exports) {
        module.exports = InsightExporter;
    }
})(typeof window !== 'undefined' ? window : global);
